import React, { useState } from 'react';
import { Button, Input, Row, Col, UncontrolledTooltip, ButtonDropdown, DropdownToggle, DropdownMenu, Label, Form } from "reactstrap";
import EmojiPicker from 'emoji-picker-react';
import { useSelector } from 'react-redux';
import RecordingModal from "./components/RecordingModal";


function ChatInput(props) {
    const [textMessage, settextMessage] = useState("");
    const [isOpen, setisOpen] = useState(false);
    const [isSending, setIsSending] = useState(false);
    const [showModal, setShowModal] = useState(false);


    const [file, setfile] = useState({
        name: "",
        size: ""
    });
    const activeMeetingId = useSelector( state => state.Chat.activeMeetingId);

    const [fileImage, setfileImage] = useState("")

    const toggle = () => setisOpen(!isOpen);

    //function for text input value change
    const handleChange = e => {
        settextMessage(e.target.value);
    }

    const onEmojiClick = (event) => {
        settextMessage(textMessage + event.emoji);
    };

    // Build fields for ask gemini API
    const authUser = JSON.parse(localStorage.getItem("authUser"));

    const userId = authUser.user_id;
    const username = authUser.username;

    //function for file input change
    const handleFileChange = async (e) => {
        if (e.target.files.length === 0) {
            alert("Please select a meeting file to upload.");
            return;
        }
        
        const selectedFile = e.target.files[0];
        
        // Save file name and size locally
        setfile({
            name: selectedFile.name,
            size: selectedFile.size,
        });

        // Display file message in chat
        props.onaddMessage(selectedFile, "fileMessage");

        // Prepare upload
        const formData = new FormData();
        formData.append("file", selectedFile);
        const authUser = JSON.parse(localStorage.getItem("authUser") || "{}");
        formData.append("speaker", authUser.username);
        formData.append("user_id", authUser.user_id);

        try {
            const token = localStorage.getItem("access_token");
            const BASE_URL = "http://localhost:5002/api";
            const res = await fetch(`${BASE_URL}/meetings/${activeMeetingId}/upload-material`, {
                method: "POST",
                body: formData,
            });

            if (res.ok) {
                const result = await res.json();
                if (props.onFetchMessages) {
                    props.onFetchMessages();  // Fetch chat records generated by backend
                }
                if (props.onMaterialUploaded) {
                    props.onMaterialUploaded();  // Update material status and enable analysis button
                }
            } else {
                if (res.status === 404) {
                    alert("Meeting not found. Please make sure you have selected a valid meeting.");
                } else {
                    const msg = await res.text();
                    alert(`Upload failed: ${msg || 'Unknown error occurred'}`);
                }
            }
        } catch (err) {
            alert("Network error: Unable to upload file. Please check your connection and try again.");
        }
    };

    //function for image input change
    const handleImageChange = e => {
        if (e.target.files.length !== 0)
            setfileImage(URL.createObjectURL(e.target.files[0]))
    }

    //function for send data to onaddMessage function(in userChat/index.js component)
    const onaddMessage = async (e, textMessage) => {
        e.preventDefault();
        // Disable input when calling ask-gemini API
        setIsSending(true);

        // Build fields for ask gemini API
        const authUser = JSON.parse(localStorage.getItem("authUser"));

        const userId = authUser.user_id;
        const username = authUser.username;

        const newMessage = {
            content: textMessage,
            meeting_id: activeMeetingId,
            user_id: userId,
            speaker: username
          };
        
        // If text value is not empty then call onaddMessage function
        if (textMessage !== "") {

            try {
                const res  = await fetch(`http://localhost:5002/api/api/ask-gemini`, {
                  method: "POST",
                  headers: {
                    "Content-Type": "application/json"
                  },
                  body: JSON.stringify(newMessage)
                });
            
                if (res.ok) {
                  props.onaddMessage(textMessage, "textMessage"); // Add to frontend display
                  settextMessage(""); // Clear input box

                  if (props.onFetchMessages) {
                    props.onFetchMessages();
                  }

                  setIsSending(false); 
                } else {
                  const errorText = await res.text();
                }
              } catch (err) {
              }

            settextMessage("");

        }

        //if file input value is not empty then call onaddMessage function
        if (file.name !== "") {
            props.onaddMessage(file, "fileMessage");
            setfile({
                name: "",
                size: ""
            })
        }

        //if image input value is not empty then call onaddMessage function
        if (fileImage !== "") {
            props.onaddMessage(fileImage, "imageMessage");
            setfileImage("")
        }
    }
    
    return (
        <React.Fragment>
            <div className="chat-input-section p-3 p-lg-4 border-top mb-0 ">
                <Form onSubmit={(e) => onaddMessage(e, textMessage)} >
                    <Row className='g-0'>
                        <Col>
                            <div>
                                <Input type="text" value={textMessage} onChange={handleChange} className="form-control form-control-lg bg-light border-light" placeholder="Enter Message..." />
                            </div>
                        </Col>
                        <Col xs="auto">
                            <div className="chat-input-links ms-md-2">
                                <ul className="list-inline mb-0 ms-0">
                                    <li className="list-inline-item">
                                        <ButtonDropdown className="emoji-dropdown" direction="up" isOpen={isOpen} toggle={toggle}>
                                            <DropdownToggle id="emoji" color="link" className="text-decoration-none font-size-16 btn-lg waves-effect">
                                                <i className="ri-emotion-happy-line"></i>
                                            </DropdownToggle>
                                            <DropdownMenu className="dropdown-menu-end">
                                                <EmojiPicker onEmojiClick={onEmojiClick} />
                                            </DropdownMenu>
                                        </ButtonDropdown>
                                        <UncontrolledTooltip target="emoji" placement="top">
                                            Emoji
                                        </UncontrolledTooltip>
                                    </li>
                                    <li className="list-inline-item input-file">
                                        <Label id="files" className="btn btn-link text-decoration-none font-size-16 btn-lg waves-effect">
                                            <i className="ri-attachment-line"></i>
                                            <Input onChange={(e) => handleFileChange(e)} type="file" name="fileInput" size="60" />
                                        </Label>
                                        <UncontrolledTooltip target="files" placement="top">
                                            Upload File
                                        </UncontrolledTooltip>
                                    </li>
                                    <li className="list-inline-item">
                                        <Button type="submit" disabled={isSending} color="primary" className="font-size-16 btn-lg chat-send waves-effect waves-light">
                                            <i className="ri-send-plane-2-fill"></i>
                                        </Button>
                                    </li>
                                    <li className="list-inline-item ms-2">
                                    <Button
                                        type="button"
                                        color="primary"
                                        className="font-size-16 btn-lg chat-send waves-effect waves-light"
                                        onClick={() => setShowModal(true)}
                                    >
                                        <i className="ri-mic-fill"></i>
                                    </Button>
                                        {showModal && (
                                            <RecordingModal 
                                                onClose={() => setShowModal(false)} 
                                                setIsSending={setIsSending}
                                                meetingId={activeMeetingId}
                                                userId={userId}
                                                username={username}
                                                onFetchMessages={props.onFetchMessages}
                                                setShowModal={setShowModal}
                                            />
                                        )} 
                                    </li>
                                </ul>
                            </div>
                        </Col>
                    </Row>
                </Form>
            </div>
        </React.Fragment>
    );
}

export default ChatInput;